"""Section (class meeting) data for the schedule builder.

Owner: Ryan Travers.

The repo has no real section data (meeting times, seats). Until the team gets a real term's
schedule of classes, `make_sample_sections()` generates a SYNTHETIC term so the builder can be run
and tested. Every generated file is marked synthetic. Replace it with real data in the same format:

    {"term": "Spring 2027", "synthetic": true,
     "sections": [{"crn": "S0001", "course": "COMP 280", "section": "001",
                   "meetings": [{"days": "MWF", "start": "09:00", "end": "09:50"}],
                   "capacity": 35, "seats_open": 4}]}

Run `python src/schedule/sections.py` to regenerate data/sections/sample_term.json.
"""
from __future__ import annotations

import json
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src" / "audit"))
from degree_audit import load_courses, norm  # noqa: E402

DAY_INDEX = {"M": 0, "T": 1, "W": 2, "R": 3, "F": 4}


def to_min(hhmm: str) -> int:
    h, m = hhmm.split(":")
    return int(h) * 60 + int(m)


def meeting_blocks(section):
    """Yield (start, end) in minutes since Monday 00:00 for every meeting of a section."""
    for mt in section["meetings"]:
        s, e = to_min(mt["start"]), to_min(mt["end"])
        for d in mt["days"]:
            yield DAY_INDEX[d] * 1440 + s, DAY_INDEX[d] * 1440 + e


def sections_overlap(a, b) -> bool:
    return any(s1 < e2 and s2 < e1 for s1, e1 in meeting_blocks(a) for s2, e2 in meeting_blocks(b))


def blocked_by(section, avoid_times) -> bool:
    """avoid_times = [{"days": "MWF", "start": "08:00", "end": "09:00"}, ...]  (student preference)."""
    return sections_overlap(section, {"meetings": avoid_times}) if avoid_times else False


def load_sections(path):
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    by_course = {}
    for s in data["sections"]:
        s = {**s, "course": norm(s["course"])}
        by_course.setdefault(s["course"], []).append(s)
    return data, by_course


# ---------------------------------------------------------------- synthetic generator
MWF = [f"{h:02d}:00" for h in range(8, 16)]                    # 50-minute slots
TR = ["08:00", "09:30", "11:00", "12:30", "14:00", "15:30"]     # 75-minute slots


def _plus(hhmm, minutes):
    t = to_min(hhmm) + minutes
    return f"{t // 60:02d}:{t % 60:02d}"


def make_sample_sections(courses, term="Spring 2027 (SYNTHETIC)", seed=365):
    rng = random.Random(seed)
    out = []
    for code in sorted(courses):
        credits = float(courses[code].get("credits", 3))
        n = rng.choice([1, 1, 2, 2, 3])
        for i in range(n):
            if rng.random() < 0.55:
                start = rng.choice(MWF)
                meetings = [{"days": "MWF", "start": start, "end": _plus(start, 50)}]
            else:
                start = rng.choice(TR)
                meetings = [{"days": "TR", "start": start, "end": _plus(start, 75)}]
            if credits >= 4:   # lab block
                day = rng.choice("MTWR")
                meetings.append({"days": day, "start": "16:00", "end": "17:50"})
            cap = rng.choice([25, 30, 35, 40])
            open_ = 0 if rng.random() < 0.12 else rng.randint(1, cap)
            out.append({"crn": f"S{len(out) + 1:04d}", "course": code, "section": f"{i + 1:03d}",
                        "meetings": meetings, "capacity": cap, "seats_open": open_})
    return {"_note": "SYNTHETIC section data generated by src/schedule/sections.py for testing. "
                     "Not N.C. A&T's real schedule of classes. Replace with a real term in the same format.",
            "term": term, "synthetic": True, "sections": out}


if __name__ == "__main__":
    data = make_sample_sections(load_courses(ROOT / "data" / "courses.json"))
    dest = ROOT / "data" / "sections" / "sample_term.json"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(json.dumps(data, indent=1), encoding="utf-8")
    print(f"wrote {len(data['sections'])} synthetic sections to {dest.relative_to(ROOT)}")
